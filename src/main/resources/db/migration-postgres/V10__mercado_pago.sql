-- Mercado Pago por loja (multitenant): conexao OAuth por loja + rastreio de pagamento externo + idempotencia de webhooks.
CREATE TABLE store_payment_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id BIGINT NOT NULL UNIQUE REFERENCES stores(id),
  provider VARCHAR(20) NOT NULL DEFAULT 'MERCADO_PAGO',
  mode VARCHAR(12) NOT NULL DEFAULT 'TEST',
  status VARCHAR(16) NOT NULL DEFAULT 'DISCONNECTED',
  mp_user_id VARCHAR(40),
  access_token_enc TEXT,
  refresh_token_enc TEXT,
  token_expires_at TIMESTAMP,
  public_key VARCHAR(200),
  connected_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
