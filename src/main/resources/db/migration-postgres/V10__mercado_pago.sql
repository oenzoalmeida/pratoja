ALTER TABLE payments ADD COLUMN qr_code_base64 TEXT;
ALTER TABLE payments ADD COLUMN ticket_url VARCHAR(500);
ALTER TABLE payments ADD COLUMN paid_at TIMESTAMP;
CREATE UNIQUE INDEX uq_payments_reference ON payments(reference);
CREATE TABLE processed_webhook_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider VARCHAR(20) NOT NULL,
  event_key VARCHAR(160) NOT NULL,
  received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_processed_webhook_event UNIQUE (provider, event_key)
);
